export function nR(e, t = Date.now(), n = 40) {
  let s = Math.floor(t / (n * 6e4));
  for (let r = 0; r < e.length; r++) s = (s * 31 + e.charCodeAt(r)) >>> 0;
  return qa[s % qa.length];
}
